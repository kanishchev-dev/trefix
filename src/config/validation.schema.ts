import * as Joi from 'joi';

/**
 * A value that must be provided explicitly in production. Outside production a
 * fixed development value keeps local setups and tests running without a full `.env`.
 */
const requiredInProduction = (developmentDefault: string, schema: Joi.StringSchema = Joi.string()): Joi.StringSchema =>
  schema.when('NODE_ENV', {
    is: 'production',
    then: Joi.required(),
    otherwise: Joi.optional().default(developmentDefault),
  });

export const validationSchema = Joi.object({
  NODE_ENV: Joi.string().valid('development', 'production', 'test', 'provision').default('development'),
  PORT: Joi.number().default(3000),
  LOG_LEVEL: Joi.string().valid('debug', 'info', 'warn', 'error').default('info'),
  CORS_ORIGINS: Joi.string().default('http://localhost:3000,http://localhost:3001,http://localhost:5173'),
  SWAGGER_ENABLED: Joi.boolean().when('NODE_ENV', {
    is: 'production',
    then: Joi.boolean().default(false),
    otherwise: Joi.boolean().default(true),
  }),
  WEB_APP_URL: Joi.string().uri().default('http://localhost:3001'),
  // Public URL of this API: OAuth redirect URIs and absolute links are built from it.
  API_BASE_URL: requiredInProduction('http://localhost:3000', Joi.string().uri()),
  THROTTLE_LIMIT: Joi.number().default(300),
  THROTTLE_TTL: Joi.number().default(60000),
  ACTIVITY_RETENTION_DAYS: Joi.number().integer().min(30).default(730),
  // Day boundaries of the analytics dashboard when the request names no timezone.
  ANALYTICS_DEFAULT_TIMEZONE: Joi.string().default('Europe/Moscow'),
  // JSON: { "<model>": { "input": usd, "cachedInput": usd, "output": usd } } per 1M tokens; overrides built-in prices.
  LLM_PRICING: Joi.string().allow('').optional(),
  // Expo access token; required only when "Enhanced push security" is on in the Expo project.
  EXPO_ACCESS_TOKEN: Joi.string().allow('').optional(),
  NOTIFICATIONS_PUSH_ENABLED: Joi.boolean().default(true),
  TRAINING_PLANS_PER_ATHLETE_LIMIT: Joi.number().integer().positive().default(100),
  TRAINING_PLAN_CREATE_RATE_LIMIT: Joi.number().integer().positive().default(30),
  DB_HOST: Joi.string().required(),
  DB_PORT: Joi.number().default(5432),
  DB_USERNAME: Joi.string().required(),
  DB_PASSWORD: Joi.string().required(),
  DB_DATABASE: Joi.string().required(),
  REDIS_HOST: Joi.string().default('localhost'),
  REDIS_PORT: Joi.number().default(6379),
  MAIL_HOST: Joi.string().required(),
  MAIL_PORT: Joi.number().default(587),
  MAIL_USER: Joi.string().required(),
  MAIL_PASSWORD: Joi.string().required(),
  MAIL_FROM: Joi.string().required(),
  MAIL_FROM_NAME: Joi.string().required(),
  MAIL_SECURE: Joi.boolean().default(false),
  MAIL_ALLOW_FROM_OVERRIDE: Joi.boolean().default(false),
  MAIL_USE_QUEUE: Joi.boolean().default(false),
  S3_ENDPOINT: Joi.string().uri().required(),
  S3_REGION: Joi.string().required(),
  S3_BUCKET: Joi.string().required(),
  S3_ACCESS_KEY: Joi.string().required(),
  S3_SECRET_KEY: Joi.string().required(),
  S3_FORCE_PATH_STYLE: Joi.boolean().default(true),
  STORAGE_MAX_FILE_SIZE: Joi.number().positive().integer().default(52428800),
  JWT_ACCESS_SECRET: Joi.string().required(),
  JWT_ACCESS_EXPIRATION: Joi.string().default('1h'),
  TRUST_PROXY: Joi.string().default('loopback, uniquelocal'),
  GEOIP_CITY_DB_PATH: Joi.string().optional(),
  AUTH_ACCESS_TOKEN_SECRET: Joi.string().optional(),
  AUTH_ACCESS_TOKEN_EXPIRES_IN: Joi.string().default('15m'),
  AUTH_REFRESH_TOKEN_SECRET: Joi.string().required(),
  AUTH_REFRESH_TOKEN_EXPIRES_IN: Joi.string().default('30d'),
  AUTH_EMAIL_CODE_EXPIRES_IN: Joi.string().default('10m'),
  AUTH_PASSWORD_RESET_EXPIRES_IN: Joi.string().default('15m'),
  AUTH_EMAIL_CODE_RESEND_COOLDOWN: Joi.string().default('60s'),
  GOOGLE_OAUTH_CLIENT_ID: Joi.string().optional(),
  GOOGLE_OAUTH_CLIENT_SECRET: Joi.string().optional(),
  APPLE_OAUTH_CLIENT_ID: Joi.string().optional(),
  APPLE_OAUTH_TEAM_ID: Joi.string().optional(),
  APPLE_OAUTH_KEY_ID: Joi.string().optional(),
  APPLE_OAUTH_PRIVATE_KEY: Joi.string().optional(),
  APPLE_OAUTH_PRIVATE_KEY_PATH: Joi.string().optional(),
  OPENAI_API_KEY: Joi.string().optional(),
  OPENAI_BASE_URL: Joi.string().uri().default('https://api.openai.com/v1'),
  OPENAI_MODEL: Joi.string().default('gpt-5'),
  OPENAI_TIMEOUT_MS: Joi.number().positive().integer().default(30000),
  OPENAI_MAX_OUTPUT_TOKENS: Joi.number().positive().integer().default(1200),
  OPENAI_TEMPERATURE: Joi.number().min(0).max(2).default(0.2),
  OPENAI_TRACING_ENABLED: Joi.boolean().default(false),
  AUTO_SEED_SYSTEM_DATA: Joi.boolean().default(true),
  ADMIN_EMAIL: Joi.string().email().optional(),
  ADMIN_PASSWORD: Joi.string().min(8).optional(),
  STRAVA_CLIENT_ID: requiredInProduction('12345'),
  STRAVA_CLIENT_SECRET: requiredInProduction('strava_client_secret_placeholder'),
  STRAVA_REDIRECT_URI: requiredInProduction('http://localhost:3000/integrations/strava/callback', Joi.string().uri()),
  STRAVA_WEBHOOK_VERIFY_TOKEN: requiredInProduction('trefix_strava_webhook_secret'),
  STRAVA_WEBHOOK_SUBSCRIPTION_ID: Joi.string().allow('').optional(),
  STRAVA_API_BASE_URL: Joi.string().uri().default('https://www.strava.com/api/v3'),
  STRAVA_OAUTH_BASE_URL: Joi.string().uri().default('https://www.strava.com/oauth'),
  HEALTH_INTEGRATIONS_ENABLED: Joi.string().valid('true', 'false').optional().default('false'),
  // Encrypts provider OAuth tokens at rest; rotating it invalidates every stored token.
  INTEGRATIONS_ENCRYPTION_KEY: requiredInProduction(
    'default_integrations_master_encryption_key_32_chars!',
    Joi.string().min(32),
  ),
});

import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';

import type {
  PlanDiff,
  PlanDiffAdjustment,
  PlanDiffWeek,
  PlanDiffWorkout,
  RelativeWeek,
  RelativeWorkout,
} from '../engine/engine.types';
import type { TrainingPlanMetricsSnapshot } from '../entities/training-plan.entity';
import type { CurrentMetrics } from '../plans/athlete-metrics.service';
import type { PlanWorkoutItem } from '../plans/plan-list.service';
import {
  PLAN_METRICS_SOURCES,
  WORKOUT_STATUSES,
  WORKOUT_TYPES,
  type WorkoutStatus,
  type WorkoutType,
} from '../training.constants';

/**
 * Response shapes of plan JSON columns and engine results. They are stored or
 * computed as plain objects; these classes only describe them in OpenAPI so the
 * client contract can be generated.
 */

const DIFF_CHANGES = ['added', 'removed', 'modified'] as const;

export class PlanConfigScheduleDto {
  @ApiPropertyOptional({ type: [Number], description: 'Weekdays, 0 = Monday' })
  trainingDays?: number[];

  @ApiPropertyOptional({ type: Number, nullable: true })
  preferredLongRunDay?: number | null;

  @ApiPropertyOptional({ type: Number, nullable: true })
  workoutDurationMinutes?: number | null;
}

export class PlanConfigStructureDto {
  @ApiPropertyOptional()
  totalWeeks?: number;

  @ApiPropertyOptional()
  sessionsPerWeek?: number;

  @ApiPropertyOptional({ type: [String] })
  focus?: string[];
}

/** Parameters the plan was built from; plans generated by the engine may store only part of them. */
export class PlanConfigDto {
  @ApiProperty({
    type: 'object',
    additionalProperties: true,
    description: 'Goal snapshot (type, target, targetDate, …)',
  })
  goal!: Record<string, unknown>;

  @ApiProperty({ type: PlanConfigScheduleDto })
  schedule!: PlanConfigScheduleDto;

  @ApiProperty({ type: PlanConfigStructureDto })
  structure!: PlanConfigStructureDto;
}

export class RecentResultDto {
  @ApiProperty()
  distance!: string;

  @ApiProperty()
  timeSeconds!: number;

  @ApiProperty()
  date!: string;
}

/** Metrics captured when the plan started; the "before" side of rebuild diffs. */
export class MetricsSnapshotDto implements TrainingPlanMetricsSnapshot {
  @ApiProperty()
  capturedAt!: string;

  @ApiPropertyOptional({ type: Number, nullable: true })
  thresholdPaceSecondsPerKm?: number | null;

  @ApiPropertyOptional({ type: Number, nullable: true })
  thresholdHeartRate?: number | null;

  @ApiPropertyOptional({ type: Number, nullable: true })
  maxHeartRate?: number | null;

  @ApiPropertyOptional({ type: Number, nullable: true })
  restingHeartRate?: number | null;

  @ApiPropertyOptional({ type: Number, nullable: true })
  weeklyMileageKm?: number | null;

  @ApiPropertyOptional({ type: Number, nullable: true })
  longestRunKm?: number | null;

  @ApiPropertyOptional({ type: RecentResultDto, nullable: true })
  recentResult?: RecentResultDto | null;

  @ApiPropertyOptional()
  source?: string;
}

export class SourcedNumberDto {
  @ApiProperty({ type: Number, nullable: true })
  value!: number | null;

  @ApiProperty({ enum: PLAN_METRICS_SOURCES })
  source!: (typeof PLAN_METRICS_SOURCES)[number];
}

export class SourcedRecentResultDto {
  @ApiProperty({ type: RecentResultDto, nullable: true })
  value!: RecentResultDto | null;

  @ApiProperty({ enum: PLAN_METRICS_SOURCES })
  source!: (typeof PLAN_METRICS_SOURCES)[number];
}

/** Current estimate of the athlete's metrics with the provenance of every value. */
export class CurrentMetricsDto implements CurrentMetrics {
  @ApiProperty({ type: SourcedNumberDto })
  thresholdPaceSecondsPerKm!: SourcedNumberDto;

  @ApiProperty({ type: SourcedNumberDto })
  thresholdHeartRate!: SourcedNumberDto;

  @ApiProperty({ type: SourcedNumberDto })
  maxHeartRate!: SourcedNumberDto;

  @ApiProperty({ type: SourcedNumberDto })
  restingHeartRate!: SourcedNumberDto;

  @ApiProperty({ type: SourcedNumberDto })
  weeklyMileageKm!: SourcedNumberDto;

  @ApiProperty({ type: SourcedNumberDto })
  longestRunKm!: SourcedNumberDto;

  @ApiProperty({ type: SourcedRecentResultDto })
  recentResult!: SourcedRecentResultDto;
}

export class PlanDiffAdjustmentDto implements PlanDiffAdjustment {
  @ApiProperty({ description: 'Stable code, e.g. VOLUME_SCALED' })
  code!: string;

  @ApiPropertyOptional({ type: 'object', additionalProperties: true })
  params?: Record<string, unknown>;
}

export class PlanDiffWorkoutDto implements PlanDiffWorkout {
  @ApiProperty()
  key!: string;

  @ApiProperty({ enum: DIFF_CHANGES })
  change!: (typeof DIFF_CHANGES)[number];

  @ApiPropertyOptional({
    type: 'object',
    additionalProperties: { type: 'array', minItems: 2, maxItems: 2, items: {} },
    description: 'Changed fields as [before, after]',
  })
  fields?: Record<string, [unknown, unknown]>;

  @ApiPropertyOptional()
  reason?: string;
}

export class PlanDiffWeekDto implements PlanDiffWeek {
  @ApiProperty()
  weekNumber!: number;

  @ApiProperty({ enum: DIFF_CHANGES })
  change!: (typeof DIFF_CHANGES)[number];

  @ApiProperty({ type: [PlanDiffWorkoutDto] })
  workouts!: PlanDiffWorkoutDto[];
}

export class BeforeAfterSeriesDto {
  @ApiProperty({ type: [Number] })
  before!: number[];

  @ApiProperty({ type: [Number] })
  after!: number[];
}

export class BeforeAfterNumberDto {
  @ApiProperty({ type: Number, nullable: true })
  before!: number | null;

  @ApiProperty({ type: Number, nullable: true })
  after!: number | null;
}

export class PlanDiffSummaryDto {
  @ApiProperty({ type: BeforeAfterSeriesDto })
  weeklyVolumeKm!: BeforeAfterSeriesDto;

  @ApiProperty({ type: BeforeAfterNumberDto })
  peakWeekKm!: BeforeAfterNumberDto;

  @ApiProperty({ type: BeforeAfterNumberDto })
  longestRunKm!: BeforeAfterNumberDto;

  @ApiProperty({ type: BeforeAfterNumberDto })
  thresholdPace!: BeforeAfterNumberDto;

  @ApiProperty({ type: BeforeAfterNumberDto })
  totalWeeks!: BeforeAfterNumberDto;

  @ApiProperty({ type: [PlanDiffAdjustmentDto] })
  adjustments!: PlanDiffAdjustmentDto[];
}

/** What changes between two versions of a plan. */
export class PlanDiffDto implements PlanDiff {
  @ApiProperty({ type: PlanDiffSummaryDto })
  summary!: PlanDiffSummaryDto & PlanDiff['summary'];

  @ApiProperty({ type: [PlanDiffWeekDto] })
  weeks!: PlanDiffWeekDto[];
}

export class PreviousResultDto {
  @ApiProperty()
  timeSeconds!: number;

  @ApiProperty()
  workoutId!: string;
}

/** Suggested goal date for "prepare again" and the result reached in the source plan. */
export class GoalSuggestionDto {
  @ApiProperty({ type: String, nullable: true })
  targetDate!: string | null;

  @ApiProperty({ type: String, nullable: true })
  previousTargetDate!: string | null;

  @ApiProperty({ type: PreviousResultDto, nullable: true })
  previousResult!: PreviousResultDto | null;
}

export class PlanListMetaDto {
  @ApiProperty()
  page!: number;

  @ApiProperty()
  limit!: number;

  @ApiProperty()
  total!: number;

  @ApiProperty()
  hasNext!: boolean;
}

/** Workout of a relative (undated) plan structure; `key` is stable across edits. */
export class RelativeWorkoutDto implements RelativeWorkout {
  @ApiProperty()
  key!: string;

  @ApiProperty({ description: '0 = Monday' })
  dayOfWeek!: number;

  @ApiProperty()
  orderInWeek!: number;

  @ApiProperty({ enum: WORKOUT_TYPES })
  type!: WorkoutType;

  @ApiProperty()
  phase!: string;

  @ApiPropertyOptional()
  title?: string;

  @ApiProperty()
  durationMinutes!: number;

  @ApiProperty()
  distanceKm!: number;

  @ApiProperty({ type: 'object', additionalProperties: true })
  target!: Record<string, unknown>;

  @ApiProperty({ type: 'array', items: { type: 'object', additionalProperties: true } })
  steps!: Array<Record<string, unknown>>;
}

/** Week of a relative plan structure (drafts, rebuild previews). */
export class RelativeWeekDto implements RelativeWeek {
  @ApiProperty()
  weekNumber!: number;

  @ApiProperty()
  phase!: string;

  @ApiPropertyOptional({ type: String, nullable: true })
  title?: string;

  @ApiPropertyOptional({ type: String, nullable: true })
  intent?: string;

  @ApiPropertyOptional({ type: Number, nullable: true })
  weeklyLoadTarget?: number;

  @ApiProperty({ type: [RelativeWorkoutDto] })
  workouts!: RelativeWorkoutDto[];
}

/** Stored week record of a plan: relative on drafts (`workouts`), dated otherwise (`workoutIds`). */
export class PlanDetailsWeekDto {
  @ApiProperty()
  weekNumber!: number;

  @ApiProperty()
  phase!: string;

  @ApiPropertyOptional({ type: String, nullable: true })
  title?: string | null;

  @ApiPropertyOptional({ type: String, nullable: true })
  intent?: string | null;

  @ApiPropertyOptional({ type: Number, nullable: true })
  weeklyLoadTarget?: number | null;

  @ApiPropertyOptional({ type: [RelativeWorkoutDto], description: 'Drafts only' })
  workouts?: RelativeWorkoutDto[];

  @ApiPropertyOptional({ type: [String], description: 'Dated plans only' })
  workoutIds?: string[];
}

/** Planned or actual workout of a dated plan. */
export class PlanWorkoutItemDto implements PlanWorkoutItem {
  @ApiProperty()
  id!: string;

  @ApiProperty()
  weekNumber!: number;

  @ApiProperty()
  orderInWeek!: number;

  @ApiProperty()
  scheduledAt!: string;

  @ApiProperty({ enum: WORKOUT_TYPES })
  type!: WorkoutType;

  @ApiProperty({ enum: WORKOUT_STATUSES })
  status!: WorkoutStatus;

  @ApiProperty()
  durationMinutes!: number;

  @ApiProperty()
  distanceKm!: number;

  @ApiProperty({ type: 'object', additionalProperties: true })
  target!: Record<string, unknown>;

  @ApiProperty({ type: 'object', additionalProperties: true, nullable: true })
  actual!: Record<string, unknown> | null;
}
